use crate::keys::*;

/// Returns `(evdev_key_code, needs_shift)` for printable ASCII chars.
/// Returns `None` for chars with no direct uinput representation.
pub fn char_to_key(c: char) -> Option<(u16, bool)> {
    Some(match c {
        'a' => (KEY_A, false),
        'b' => (KEY_B, false),
        'c' => (KEY_C, false),
        'd' => (KEY_D, false),
        'e' => (KEY_E, false),
        'f' => (KEY_F, false),
        'g' => (KEY_G, false),
        'h' => (KEY_H, false),
        'i' => (KEY_I, false),
        'j' => (KEY_J, false),
        'k' => (KEY_K, false),
        'l' => (KEY_L, false),
        'm' => (KEY_M, false),
        'n' => (KEY_N, false),
        'o' => (KEY_O, false),
        'p' => (KEY_P, false),
        'q' => (KEY_Q, false),
        'r' => (KEY_R, false),
        's' => (KEY_S, false),
        't' => (KEY_T, false),
        'u' => (KEY_U, false),
        'v' => (KEY_V, false),
        'w' => (KEY_W, false),
        'x' => (KEY_X, false),
        'y' => (KEY_Y, false),
        'z' => (KEY_Z, false),
        'A' => (KEY_A, true),
        'B' => (KEY_B, true),
        'C' => (KEY_C, true),
        'D' => (KEY_D, true),
        'E' => (KEY_E, true),
        'F' => (KEY_F, true),
        'G' => (KEY_G, true),
        'H' => (KEY_H, true),
        'I' => (KEY_I, true),
        'J' => (KEY_J, true),
        'K' => (KEY_K, true),
        'L' => (KEY_L, true),
        'M' => (KEY_M, true),
        'N' => (KEY_N, true),
        'O' => (KEY_O, true),
        'P' => (KEY_P, true),
        'Q' => (KEY_Q, true),
        'R' => (KEY_R, true),
        'S' => (KEY_S, true),
        'T' => (KEY_T, true),
        'U' => (KEY_U, true),
        'V' => (KEY_V, true),
        'W' => (KEY_W, true),
        'X' => (KEY_X, true),
        'Y' => (KEY_Y, true),
        'Z' => (KEY_Z, true),
        '1' => (KEY_1, false),
        '2' => (KEY_2, false),
        '3' => (KEY_3, false),
        '4' => (KEY_4, false),
        '5' => (KEY_5, false),
        '6' => (KEY_6, false),
        '7' => (KEY_7, false),
        '8' => (KEY_8, false),
        '9' => (KEY_9, false),
        '0' => (KEY_0, false),
        '!' => (KEY_1, true),
        '@' => (KEY_2, true),
        '#' => (KEY_3, true),
        '$' => (KEY_4, true),
        '%' => (KEY_5, true),
        '^' => (KEY_6, true),
        '&' => (KEY_7, true),
        '*' => (KEY_8, true),
        '(' => (KEY_9, true),
        ')' => (KEY_0, true),
        ' ' => (KEY_SPACE, false),
        '\n' => (KEY_ENTER, false),
        '-' => (KEY_MINUS, false),
        '_' => (KEY_MINUS, true),
        '=' => (KEY_EQUAL, false),
        '+' => (KEY_EQUAL, true),
        '[' => (KEY_LEFTBRACE, false),
        '{' => (KEY_LEFTBRACE, true),
        ']' => (KEY_RIGHTBRACE, false),
        '}' => (KEY_RIGHTBRACE, true),
        ';' => (KEY_SEMICOLON, false),
        ':' => (KEY_SEMICOLON, true),
        '\'' => (KEY_APOSTROPHE, false),
        '"' => (KEY_APOSTROPHE, true),
        ',' => (KEY_COMMA, false),
        '<' => (KEY_COMMA, true),
        '.' => (KEY_DOT, false),
        '>' => (KEY_DOT, true),
        '/' => (KEY_SLASH, false),
        '?' => (KEY_SLASH, true),
        '\\' => (KEY_BACKSLASH, false),
        '|' => (KEY_BACKSLASH, true),
        '`' => (KEY_GRAVE, false),
        '~' => (KEY_GRAVE, true),
        _ => return None,
    })
}
